#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["pyyaml>=6"]
# ///
"""Assemble agent.md (and deployment-<agent>.yaml) from the layered files of one agent folder.

`ant apply` reads one agent.md (frontmatter = config, body = system prompt). People read and edit
better one concern per file, so each agent folder keeps the parts and this script builds the file
`ant apply` needs. Never edit the generated files by hand: the next run overwrites them.

Usage:
  uv run --script <skill>/scripts/ensamblar.py agents/<name> [agents/<other> ...]
  uv run --script <skill>/scripts/ensamblar.py --check agents/<name>    # exit 1 if a generated file is stale

Parts (in agents/<name>/; only the first two are required):
  model.yaml          name, description, model: {id, effort}
  system_prompt.md    the system prompt (Markdown)
  tools.yaml          tools: [agent_toolset_20260401 entry, custom tools...]
  mcp.yaml            mcp_servers: [...]   toolsets: [mcp_toolset entries, appended to tools]
  skills.yaml         skills: [...]
  subagents.yaml      multiagent: {...}
  schedule.yaml       name, schedule, budget, vault_ids, resources, max_iterations,
                      deployment_file (default deployment-<folder>.yaml) -> deployment
  kickoff.md          the message that starts each scheduled run
  rubric.md           if present, the kickoff becomes user.define_outcome with this rubric
  files.yaml          files: [{path, mount_path, file_id}] - entries with a file_id are mounted
Generated: agent.md, and the deployment file when schedule.yaml exists.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

HEADER = "GENERATED by ensamblar.py from the files in this folder. Edit those, then re-run it."


def load(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as exc:
        raise SystemExit(f"{path}: invalid YAML (quote values that contain ': '):\n{exc}") from None
    if not isinstance(data, dict):
        raise SystemExit(f"{path}: expected a YAML mapping")
    return data


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.Node:
    style = "|" if "\n" in value else None  # multi-line text stays readable as a block
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def dump(data: dict) -> str:
    return yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=1000)


def build(folder: Path) -> dict[Path, str]:
    model = load(folder / "model.yaml")
    prompt_path = folder / "system_prompt.md"
    if not model or not prompt_path.exists():
        raise SystemExit(f"{folder}: model.yaml and system_prompt.md are required")
    for key in ("name", "model"):
        if key not in model:
            raise SystemExit(f"{folder}/model.yaml: missing '{key}'")

    config: dict = {k: model[k] for k in ("name", "description", "model") if k in model}
    skills = load(folder / "skills.yaml").get("skills")
    if skills:
        config["skills"] = skills
    mcp = load(folder / "mcp.yaml")
    if mcp.get("mcp_servers"):
        config["mcp_servers"] = mcp["mcp_servers"]
    multi = load(folder / "subagents.yaml").get("multiagent")
    if multi:
        config["multiagent"] = multi
    tools = list(load(folder / "tools.yaml").get("tools") or [])
    tools += list(mcp.get("toolsets") or [])
    if tools:
        config["tools"] = tools
    servers = {s.get("name") for s in config.get("mcp_servers", [])}
    for t in tools:
        if t.get("type") == "mcp_toolset" and t.get("mcp_server_name") not in servers:
            raise SystemExit(f"{folder}/mcp.yaml: toolset for unknown server '{t.get('mcp_server_name')}'")

    prompt = prompt_path.read_text(encoding="utf-8").strip()
    out = {folder / "agent.md": f"---\n# {HEADER}\n{dump(config)}---\n\n{prompt}\n"}

    sched = load(folder / "schedule.yaml")
    if sched:
        kickoff_path = folder / "kickoff.md"
        if not kickoff_path.exists():
            raise SystemExit(f"{folder}: schedule.yaml needs kickoff.md")
        kickoff = kickoff_path.read_text(encoding="utf-8").strip() + "\n"
        rubric_path = folder / "rubric.md"
        if rubric_path.exists():
            event = {"type": "user.define_outcome", "description": kickoff,
                     "max_iterations": sched.get("max_iterations", 2),
                     "rubric": {"type": "text", "content": rubric_path.read_text(encoding="utf-8").strip() + "\n"}}
        else:
            event = {"type": "user.message", "content": [{"type": "text", "text": kickoff}]}
        resources = list(sched.get("resources") or [])
        for f in load(folder / "files.yaml").get("files") or []:
            fid = str(f.get("file_id") or "")
            if not fid.startswith("file_"):
                raise SystemExit(f"{folder}/files.yaml: {f.get('path')} has no file_id; upload it first "
                                 f"(ant files upload --file <path>) or remove the entry")
            resources.append({"type": "file", "file_id": fid, "mount_path": f["mount_path"]})
        dep: dict = {"name": sched.get("name", f"{config['name']} schedule"),
                     "agent": "./agent.md", "environment_id": "./environment.yaml"}
        for v in list(sched.get("vault_ids") or []) + [r if isinstance(r, str) else r.get("path", "") for r in resources]:
            if "<" in str(v):
                raise SystemExit(f"{folder}/schedule.yaml: placeholder left in {v!r}")
        for key in ("vault_ids", "schedule", "budget"):
            if key in sched:
                dep[key] = sched[key]
        if resources:
            dep["resources"] = resources
        dep["initial_events"] = [event]
        target = sched.get("deployment_file", f"deployment-{folder.name}.yaml")
        if not target.startswith("deployment"):
            raise SystemExit(f"{folder}/schedule.yaml: deployment_file must start with 'deployment' so ant apply sees it")
        out[folder / target] = f"# {HEADER}\n{dump(dep)}"
    return out


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv
    if not args:
        print(__doc__)
        return 2
    stale = 0
    for arg in args:
        for path, text in build(Path(arg)).items():
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current == text:
                print(f"unchanged  {path}")
            elif check:
                print(f"STALE      {path}")
                stale += 1
            else:
                path.write_text(text, encoding="utf-8")
                print(f"wrote      {path}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
